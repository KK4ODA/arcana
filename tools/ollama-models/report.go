package main

import (
	"fmt"
	"sort"
	"strings"
)

// report writes the Markdown record of a run: what was listed, what is
// offered, and why everything else was left out.
func (r *result) report(engine string) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Ollama models in the catalog\n\n")
	w("Generated by `tools/ollama-models` on %s from Project NOMAD's model list and the Ollama registry. ", r.generated.Format("2 January 2006"))
	w("Do not edit by hand; see [ADR-0028](adr/0028-ollama-registry-models.md).\n\n")

	byReason := map[string][]exclusion{}
	for _, e := range r.excluded {
		byReason[e.Reason] = append(byReason[e.Reason], e)
	}
	w("## Counts\n\n")
	w("| | Models |\n|---|---:|\n")
	w("| Listed by NOMAD | %d |\n", r.listed)
	w("| Offered in Arcana | %d |\n", len(r.offered))
	for _, reason := range []string{reasonCloud, reasonNotGGUF, reasonEmbedding, reasonEngine, reasonUntested} {
		if n := len(byReason[reason]); n > 0 {
			w("| Excluded: %s | %d |\n", reasonTitle(reason), n)
		}
	}
	w("\nThe %d offered models give %d catalog entries: one per distinct model file behind the `latest` tag and the plain size tags (`7b`, `e4b`, `30b-a3b`), which Ollama points at its default quantization for that size. ", len(r.offered), len(r.resources))
	w("%d files of offered models were left out (listed below). ", len(r.fileExcl))
	w("%d offered models are image-and-text models whose image part is a separate projector file; Arcana downloads the text model only.\n\n", len(r.textOnly))
	verified := 0
	for _, res := range r.resources {
		if res.License.Verified {
			verified++
		}
	}
	w("Licenses: %d of %d entries are verified against the publisher's statement on Hugging Face; the rest are recorded as unconfirmed with redistribution \"unknown\".\n\n", verified, len(r.resources))
	noTemplate := 0
	for _, res := range r.resources {
		if res.ProviderRef["chatTemplate"] == "none" {
			noTemplate++
		}
	}
	w("%d entries' files carry no chat template; llama.cpp's server then uses its generic ChatML template, which the model may not follow, and their descriptions say so.\n\n", noTemplate)
	w("Every offered file was loaded by %s's server (a sparse copy: the real GGUF header and zeros in place of the weights), which checks the architecture, each tensor's name, shape and type, and the file length. For %d of them the weights loaded but the 4,096-token context did not fit the test machine's 15 GB of memory; they are offered with their memory need stated.\n\n", engine, r.contextOnly)

	w("## Excluded models\n\n")
	for _, reason := range []string{reasonCloud, reasonNotGGUF, reasonEmbedding, reasonEngine, reasonUntested} {
		list := byReason[reason]
		if len(list) == 0 {
			continue
		}
		sort.Slice(list, func(i, j int) bool { return list[i].Model < list[j].Model })
		w("### %s (%d)\n\n%s\n\n", capitalise(reasonTitle(reason)), len(list), reasonText[reason])
		if reason == reasonEngine {
			w("| Model | Cause |\n|---|---|\n")
			for _, e := range list {
				w("| %s | %s |\n", e.Model, oneLine(e.Detail))
			}
			w("\n")
			continue
		}
		var names []string
		for _, e := range list {
			names = append(names, e.Model)
		}
		w("%s\n\n", strings.Join(names, ", "))
	}

	w("## Files left out of offered models\n\n")
	if len(r.fileExcl) == 0 {
		w("None.\n\n")
	} else {
		w("| Model | Tags | Reason |\n|---|---|---|\n")
		for _, e := range r.fileExcl {
			detail := reasonTitle(e.Reason)
			if e.Detail != "" {
				detail += ": " + oneLine(e.Detail)
			}
			w("| %s | %s | %s |\n", e.Model, strings.Join(e.Tags, ", "), detail)
		}
		w("\n")
	}

	w("## Offered entries\n\n")
	w("| Entry | Architecture | File | Memory | License |\n|---|---|---:|---:|---|\n")
	for _, res := range r.resources {
		lic := res.License.ID
		if !res.License.Verified {
			lic += " (unconfirmed)"
		}
		w("| %s | %s | %s | %s | %s |\n", res.Title, res.ProviderRef["architecture"], gb(res.DownloadSize),
			gbRound(res.Stats["memoryBytes"]), lic)
	}
	if len(r.hfProblems) > 0 {
		sort.Strings(r.hfProblems)
		w("\n## Publisher statements that could not be read\n\n")
		for _, p := range r.hfProblems {
			w("- %s\n", p)
		}
	}
	return b.String()
}

func reasonTitle(reason string) string {
	return map[string]string{
		reasonCloud:     "cloud only",
		reasonNotGGUF:   "no GGUF file",
		reasonEmbedding: "embedding model",
		reasonEngine:    "llamafile cannot load it",
		reasonUntested:  "not load-tested",
	}[reason]
}

func capitalise(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	s = strings.ReplaceAll(s, "|", "/")
	if len(s) > 160 {
		s = s[:160] + "…"
	}
	return s
}
