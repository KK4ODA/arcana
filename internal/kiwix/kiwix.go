// Package kiwix runs kiwix-serve (from kiwix-tools, GPL-3.0) as a separate
// process to read and serve ZIM archives, and federates its search API.
//
// Arcana does not link libzim or libkiwix. kiwix-serve listens on loopback
// only; Arcana's own server reverse-proxies to it from a separate browser
// origin, so archive content (which may contain scripts) can never call
// Arcana's management API.
