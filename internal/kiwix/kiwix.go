// URLRoot is the path prefix kiwix-serve is told to use; Arcana proxies it
// unchanged so links generated by kiwix-serve stay valid.
const URLRoot = "/kiwix"

// Archive is a ZIM file to serve.
type Archive struct {
	ResourceID string
	// Path is absolute.
	Path string
	// UUID is the ZIM's identifier when known from the catalog.
	UUID string
	// Language is the resource's primary language (BCP 47).
	Language string
	Title    string
}

// Book is an archive as kiwix-serve exposes it.
type Book struct {
	ResourceID string `json:"resourceId"`
	Name       string `json:"name"`
	UUID       string `json:"uuid"`
	Title      string `json:"title"`
	Language   string `json:"language"`
	// ContentPath is the URL path of the archive's main page.
	ContentPath string `json:"contentPath"`
}

// Status describes the sidecar for the dashboard.
type Status struct {
	State     string `json:"state"` // unavailable, idle, starting, running, failed
	Binary    string `json:"binary,omitempty"`
	Version   string `json:"version,omitempty"`
	Books     int    `json:"books"`
	LastError string `json:"lastError,omitempty"`
	Restarts  int    `json:"restarts"`
}

// Server supervises kiwix-serve.
type Server struct {
	Binary string
	// WorkDir is the directory kiwix-serve runs in (the library root).
	WorkDir string
	Log     *slog.Logger

	mu       sync.Mutex
	proc     *process
	books    map[string]Book // by resource ID
	status   Status
	archives []Archive
	client   *http.Client
	closed   bool
}

type process struct {
	cmd  *exec.Cmd
	port int
	done chan struct{}
}

// FindBinary locates kiwix-serve. Search order: explicit path; the
// library's bin/<os>-<arch>/kiwix/ and bin/<os>-<arch>/; the directory of the
// running executable; PATH.
func FindBinary(explicit, libraryRoot string) (string, error) {
	name := "kiwix-serve"
	if runtime.GOOS == "windows" {
		name += ".exe"
	}
	var candidates []string
	if explicit != "" {
		candidates = append(candidates, explicit)
	}
	if libraryRoot != "" {
		plat := buildinfo.Platform()
		candidates = append(candidates,
			filepath.Join(libraryRoot, "bin", plat, "kiwix", name),
			filepath.Join(libraryRoot, "bin", plat, name))
	}
	if exe, err := os.Executable(); err == nil {
		candidates = append(candidates, filepath.Join(filepath.Dir(exe), name),
			filepath.Join(filepath.Dir(exe), "kiwix", name))
	}
	for _, c := range candidates {
		if st, err := os.Stat(c); err == nil && !st.IsDir() {
			return c, nil
		}
	}
	if p, err := exec.LookPath(name); err == nil {
		return p, nil
	}
	return "", fmt.Errorf("kiwix-serve not found (looked in %s and PATH)", strings.Join(candidates, ", "))
}

// New creates a supervisor. Call Apply to start serving.
func New(binary, workDir string, log *slog.Logger) *Server {
	if log == nil {
		log = slog.Default()
	}
	s := &Server{Binary: binary, WorkDir: workDir, Log: log, books: map[string]Book{},
		client: &http.Client{Timeout: 30 * time.Second}}
	if binary == "" {
		s.status = Status{State: "unavailable", LastError: "kiwix-serve is not installed for this platform; ZIM archives cannot be opened"}
	} else {
		s.status = Status{State: "idle", Binary: binary}
	}
	return s
}

// Status returns the current status.
func (s *Server) Status() Status {
	s.mu.Lock()
	defer s.mu.Unlock()
	st := s.status
	st.Books = len(s.books)
	return st
}

// Books returns the served archives keyed by resource ID.
func (s *Server) Books() map[string]Book {
	s.mu.Lock()
	defer s.mu.Unlock()
	out := make(map[string]Book, len(s.books))
	for k, v := range s.books {
		out[k] = v
	}
	return out
}

// Apply makes kiwix-serve serve exactly the given archives. A new process
// is started and verified before the old one is stopped (so readers see no
// interruption, and on Windows the old process releases files that are
// about to be deleted).
func (s *Server) Apply(ctx context.Context, archives []Archive) error {
	s.mu.Lock()
	if s.closed {
		s.mu.Unlock()
		return errors.New("server closed")
	}
	if s.Binary == "" {
		s.mu.Unlock()
		return nil
	}
	sort.Slice(archives, func(i, j int) bool { return archives[i].ResourceID < archives[j].ResourceID })
	s.archives = archives
	old := s.proc
	if len(archives) == 0 {
		s.proc = nil
		s.books = map[string]Book{}
		s.status.State = "idle"
		s.status.LastError = ""
		s.mu.Unlock()
		stopProcess(old)
		return nil
	}
	s.status.State = "starting"
	s.mu.Unlock()

	proc, books, err := s.launch(ctx, archives)
	s.mu.Lock()
	if err != nil {
		s.status.State = "failed"
		s.status.LastError = err.Error()
		s.mu.Unlock()
		return err
	}
	s.proc = proc
	s.books = books
	s.status.State = "running"
	s.status.LastError = ""
	s.mu.Unlock()
	stopProcess(old)
	go s.supervise(proc)
	return nil
}

func (s *Server) launch(ctx context.Context, archives []Archive) (*process, map[string]Book, error) {
	bin, err := ensureExecutable(s.Binary)
	if err != nil {
		return nil, nil, err
	}
	var lastErr error
	for attempt := 0; attempt < 3; attempt++ {
		port, err := freePort()
		if err != nil {
			return nil, nil, err
		}
		args := []string{
			"--address=127.0.0.1",
			"--port=" + strconv.Itoa(port),
			"--urlRootLocation=" + URLRoot,
			"--blockexternal",
			"--skipInvalid",
			"--threads=4",
			"--attachToProcess=" + strconv.Itoa(os.Getpid()),
		}
		for _, a := range archives {
			args = append(args, s.relPath(a.Path))
		}
		cmd := exec.Command(bin, args...)
		cmd.Dir = s.WorkDir
		var stderr bytes.Buffer
		cmd.Stdout = io.Discard
		cmd.Stderr = &limitedWriter{buf: &stderr, max: 64 << 10}
		hideWindow(cmd)
		if err := cmd.Start(); err != nil {
			return nil, nil, fmt.Errorf("start kiwix-serve: %w", err)
		}
		p := &process{cmd: cmd, port: port, done: make(chan struct{})}
		go func() { _ = cmd.Wait(); close(p.done) }()

		books, err := s.waitReady(ctx, p, archives)
		if err == nil {
			s.Log.Info("kiwix-serve running", "port", port, "archives", len(archives))
			return p, books, nil
		}
		stopProcess(p)
		var known errStartup
		if errors.As(err, &known) {
			return nil, nil, known // retrying cannot help
		}
		lastErr = fmt.Errorf("%v: %s", err, strings.TrimSpace(stderr.String()))
	}
	return nil, nil, lastErr
}

// errStartup is a start failure with a known cause and a message for people.
type errStartup struct{ msg string }

func (e errStartup) Error() string { return e.msg }

// relPath keeps arguments short and portable by passing paths relative to
// the library root (Windows limits command lines to 32 767 characters).
func (s *Server) relPath(p string) string {
	if rel, err := filepath.Rel(s.WorkDir, p); err == nil && !strings.HasPrefix(rel, "..") {
		return rel
	}
	return p
}

func (s *Server) waitReady(ctx context.Context, p *process, archives []Archive) (map[string]Book, error) {
	deadline := time.Now().Add(30 * time.Second)
	base := fmt.Sprintf("http://127.0.0.1:%d%s", p.port, URLRoot)
	for time.Now().Before(deadline) {
		select {
		case <-p.done:
			if hint := exitHint(p.cmd.ProcessState); hint != "" {
				return nil, errStartup{hint}
			}
			return nil, errors.New("kiwix-serve exited during startup")
		case <-ctx.Done():
			return nil, ctx.Err()
		case <-time.After(100 * time.Millisecond):
		}
		resp, err := s.client.Get(base + "/catalog/v2/entries?count=-1")
		if err != nil {
			continue
		}
		data, err := io.ReadAll(io.LimitReader(resp.Body, 32<<20))
		resp.Body.Close()
		if err != nil || resp.StatusCode != http.StatusOK {
			continue
		}
		return mapBooks(data, archives)
	}
	return nil, errors.New("kiwix-serve did not become ready")
}

type localEntry struct {
	ID       string `xml:"id"`
	Title    string `xml:"title"`
	Language string `xml:"language"`
	Links    []struct {
		Type string `xml:"type,attr"`
		Href string `xml:"href,attr"`
	} `xml:"link"`
}

// mapBooks matches kiwix-serve's catalog entries to Arcana resources: first
// by the name kiwix derives from the file name, then by ZIM UUID.
func mapBooks(data []byte, archives []Archive) (map[string]Book, error) {
	var feed struct {
		Entries []localEntry `xml:"entry"`
	}
	if err := xml.Unmarshal(data, &feed); err != nil {
		return nil, err
	}
	byName := map[string]localEntry{}
	byUUID := map[string]localEntry{}
	for _, e := range feed.Entries {
		for _, l := range e.Links {
			if l.Type == "text/html" {
				name := strings.TrimPrefix(l.Href, URLRoot+"/content/")
				byName[name] = e
			}
		}
		byUUID[strings.TrimPrefix(e.ID, "urn:uuid:")] = e
	}
	books := map[string]Book{}
	for _, a := range archives {
		name := BookName(a.Path)
		e, ok := byName[name]
		if !ok && a.UUID != "" {
			if e2, ok2 := byUUID[a.UUID]; ok2 {
				e, ok = e2, true
				for _, l := range e2.Links {
					if l.Type == "text/html" {
						name = strings.TrimPrefix(l.Href, URLRoot+"/content/")
					}
				}
			}
		}
		if !ok {
			continue // kiwix-serve skipped it (invalid or unreadable archive)
		}
		books[a.ResourceID] = Book{
			ResourceID:  a.ResourceID,
			Name:        name,
			UUID:        strings.TrimPrefix(e.ID, "urn:uuid:"),
			Title:       firstNonEmpty(e.Title, a.Title),
			Language:    firstNonEmpty(a.Language, e.Language),
			ContentPath: URLRoot + "/content/" + url.PathEscape(name) + "/",
		}
	}
	return books, nil
}

// BookName reproduces libkiwix's rule for the URL name of an archive
// (Book::getHumanReadableIdFromPath) for ASCII file names: lower case,
// extension removed, spaces to underscores, "+" to "plus".
func BookName(path string) string {
	base := filepath.Base(path)
	lower := strings.ToLower(base)
	if i := strings.Index(lower, ".zim"); i >= 0 {
		base = base[:i]
	}
	base = strings.ToLower(base)
	base = strings.ReplaceAll(base, " ", "_")
	return strings.ReplaceAll(base, "+", "plus")
}

func (s *Server) supervise(p *process) {
	<-p.done
	s.mu.Lock()
	current := s.proc == p && !s.closed
	if !current {
		s.mu.Unlock()
		return
	}
	s.status.Restarts++
	restarts := s.status.Restarts
	archives := s.archives
	s.status.State = "failed"
	s.status.LastError = "kiwix-serve stopped unexpectedly"
	s.proc = nil
	s.mu.Unlock()
	s.Log.Warn("kiwix-serve exited unexpectedly; restarting", "restarts", restarts)
	if restarts > 5 {
		return
	}
	time.Sleep(time.Duration(restarts) * time.Second)
	_ = s.Apply(context.Background(), archives)
}

// Stop terminates kiwix-serve.
func (s *Server) Stop() {
	s.mu.Lock()
	s.closed = true
	p := s.proc
	s.proc = nil
	s.mu.Unlock()
	stopProcess(p)
}

func stopProcess(p *process) {
	if p == nil || p.cmd.Process == nil {
		return
	}
	_ = p.cmd.Process.Kill()
	select {
	case <-p.done:
	case <-time.After(5 * time.Second):
	}
}

func (s *Server) target() (*url.URL, bool) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.proc == nil {
		return nil, false
	}
	return &url.URL{Scheme: "http", Host: "127.0.0.1:" + strconv.Itoa(s.proc.port)}, true
}

// InjectScript, when set, is the path of a script added to every HTML page
// served from archives (Arcana's reader integration).
var InjectScript = ""

// maxInject bounds the HTML pages that are rewritten; larger pages pass
// through unchanged.
const maxInject = 16 << 20

// injectScript adds a script tag before </head> (or at the start).
func injectScript(resp *http.Response) error {
	if InjectScript == "" || resp.StatusCode != http.StatusOK ||
		!strings.HasPrefix(resp.Header.Get("Content-Type"), "text/html") || resp.Header.Get("Content-Encoding") != "" {
		return nil
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, maxInject+1))
	if err != nil {
		return err
	}
	if len(body) > maxInject {
		resp.Body = struct {
			io.Reader
			io.Closer
		}{io.MultiReader(bytes.NewReader(body), resp.Body), resp.Body}
		return nil
	}
	resp.Body.Close()
	tag := []byte(`<script src="` + InjectScript + `"></script>`)
	lower := bytes.ToLower(body)
	if i := bytes.Index(lower, []byte("</head>")); i >= 0 {
		body = append(body[:i:i], append(tag, body[i:]...)...)
	} else {
		body = append(tag, body...)
	}
	resp.Body = io.NopCloser(bytes.NewReader(body))
	resp.ContentLength = int64(len(body))
	resp.Header.Set("Content-Length", strconv.Itoa(len(body)))
	return nil
}

// Handler reverse-proxies requests under URLRoot to kiwix-serve.
func (s *Server) Handler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		target, ok := s.target()
		if !ok {
			http.Error(w, "The archive reader is not running. Check the Arcana dashboard.", http.StatusServiceUnavailable)
			return
		}
		proxy := &httputil.ReverseProxy{
			Rewrite: func(pr *httputil.ProxyRequest) {
				pr.SetURL(target)
				pr.Out.Host = target.Host
				pr.Out.Header.Del("Cookie")
				pr.Out.Header.Del("Authorization")
				// Uncompressed responses let the reader script be added.
				pr.Out.Header.Del("Accept-Encoding")
			},
			ModifyResponse: func(resp *http.Response) error {
				// kiwix-serve allows any origin to read content; Arcana
				// does not let other web pages read the library.
				resp.Header.Del("Access-Control-Allow-Origin")
				return injectScript(resp)
			},
			ErrorHandler: func(w http.ResponseWriter, r *http.Request, err error) {
				http.Error(w, "The archive reader is restarting; try again in a moment.", http.StatusBadGateway)
			},
		}
		proxy.ServeHTTP(w, r)
	})
}

// ---------------------------------------------------------------- search

// Result is one full-text search hit.
type Result struct {
	ResourceID string `json:"resourceId"`
	Book       string `json:"book"`
	Title      string `json:"title"`
	// Snippet is HTML-escaped text in which only <b> highlighting remains.
	Snippet string `json:"snippet"`
	Path    string `json:"path"`
}

type rss struct {
	Channel struct {
		Total int `xml:"totalResults"`
		Items []struct {
			Title string `xml:"title"`
			Link  string `xml:"link"`
			// innerxml: kiwix-serve marks matches with <b> child
			// elements, which chardata would silently drop.
			Description struct {
				Inner string `xml:",innerxml"`
			} `xml:"description"`
		} `xml:"item"`
	} `xml:"channel"`
}

// Search runs a full-text query. kiwix-serve only searches several archives
// at once when they share one language, so archives are grouped by
// language and the groups are queried in turn.
func (s *Server) Search(ctx context.Context, query string, only map[string]bool, limit int) ([]Result, int, error) {
	target, ok := s.target()
	if !ok {
		return nil, 0, errors.New("archive reader is not running")
	}
	if limit <= 0 || limit > 140 {
		limit = 25
	}
	groups := map[string][]Book{}
	for id, b := range s.Books() {
		if only != nil && !only[id] {
			continue
		}
		groups[b.Language] = append(groups[b.Language], b)
	}
	var results []Result
	total := 0
	var lastErr error
	langs := make([]string, 0, len(groups))
	for l := range groups {
		langs = append(langs, l)
	}
	sort.Strings(langs)
	for _, lang := range langs {
		books := groups[lang]
		byName := map[string]Book{}
		v := url.Values{}
		for _, b := range books {
			v.Add("books.name", b.Name)
			byName[b.Name] = b
		}
		v.Set("pattern", query)
		v.Set("format", "xml")
		v.Set("pageLength", strconv.Itoa(limit))
		u := target.String() + URLRoot + "/search?" + v.Encode()
		req, _ := http.NewRequestWithContext(ctx, http.MethodGet, u, nil)
		resp, err := s.client.Do(req)
		if err != nil {
			lastErr = err
			continue
		}
		data, _ := io.ReadAll(io.LimitReader(resp.Body, 8<<20))
		resp.Body.Close()
		if resp.StatusCode != http.StatusOK {
			// Archives without a full-text index return an error page.
			continue
		}
		var doc rss
		if err := xml.Unmarshal(data, &doc); err != nil {
			lastErr = err
			continue
		}
		total += doc.Channel.Total
		for _, it := range doc.Channel.Items {
			name := strings.TrimPrefix(it.Link, URLRoot+"/content/")
			if i := strings.IndexByte(name, '/'); i >= 0 {
				name = name[:i]
			}
			b := byName[name]
			results = append(results, Result{
				ResourceID: b.ResourceID,
				Book:       b.Title,
				Title:      it.Title,
				Snippet:    SanitizeSnippet(it.Description.Inner),
				Path:       it.Link,
			})
		}
	}
	if len(results) == 0 && lastErr != nil {
		return nil, 0, lastErr
	}
	return results, total, nil
}

// SanitizeSnippet converts an XML search snippet into safe HTML: text is
// unescaped and re-escaped, <b> highlighting is kept, and every other tag is
// removed.
func SanitizeSnippet(inner string) string {
	s := strings.Map(func(r rune) rune {
		if r == '\x01' || r == '\x02' {
			return -1
		}
		return r
	}, inner)
	s = strings.ReplaceAll(s, "<b>", "\x01")
	s = strings.ReplaceAll(s, "</b>", "\x02")
	s = tagRe.ReplaceAllString(s, "")
	s = html.EscapeString(html.UnescapeString(s))
	if strings.Count(s, "\x01") != strings.Count(s, "\x02") {
		s = strings.NewReplacer("\x01", "", "\x02", "").Replace(s)
	}
	return strings.NewReplacer("\x01", "<b>", "\x02", "</b>").Replace(s)
}

var tagRe = regexp.MustCompile(`<[^>]*>`)

// ---------------------------------------------------------------- helpers

func freePort() (int, error) {
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return 0, err
	}
	defer l.Close()
	return l.Addr().(*net.TCPAddr).Port, nil
}

// ensureExecutable returns a path that can be executed. Removable drives
// formatted FAT32 are mounted on Linux with "showexec", and some exFAT mounts
// clear execute bits, so a binary stored on the library drive may not be
// runnable in place. In that case it is copied once into the user's cache
// directory on the host.
func ensureExecutable(p string) (string, error) {
	if runtime.GOOS == "windows" {
		return p, nil
	}
	st, err := os.Stat(p)
	if err != nil {
		return "", err
	}
	if st.Mode()&0o111 != 0 && canExec(p) {
		return p, nil
	}
	_ = os.Chmod(p, st.Mode()|0o755)
	if st2, err := os.Stat(p); err == nil && st2.Mode()&0o111 != 0 && canExec(p) {
		return p, nil
	}
	data, err := os.ReadFile(p)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(data)
	cache, err := os.UserCacheDir()
	if err != nil {
		cache = os.TempDir()
	}
	dir := filepath.Join(cache, "arcana", "bin-"+hex.EncodeToString(sum[:8]))
	dst := filepath.Join(dir, filepath.Base(p))
	if _, err := os.Stat(dst); err == nil {
		return dst, nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(dst, data, 0o755); err != nil {
		return "", err
	}
	return dst, nil
}

// canExec checks the noexec mount flag by asking the OS.
func canExec(p string) bool {
	cmd := exec.Command(p, "--version")
	hideWindow(cmd)
	cmd.Stdout, cmd.Stderr = io.Discard, io.Discard
	err := cmd.Run()
	var ee *exec.ExitError
	return err == nil || errors.As(err, &ee)
}

type limitedWriter struct {
	buf *bytes.Buffer
	max int
}

func (l *limitedWriter) Write(p []byte) (int, error) {
	if l.buf.Len() < l.max {
		room := l.max - l.buf.Len()
		if len(p) > room {
			l.buf.Write(p[:room])
		} else {
			l.buf.Write(p)
		}
	}
	return len(p), nil
}

func firstNonEmpty(v ...string) string {
	for _, s := range v {
		if s != "" {
			return s
		}
	}
	return ""
}
